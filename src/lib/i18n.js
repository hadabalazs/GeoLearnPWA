export function t(lang, key) {
  const parts = key.split('.');
  let val = dict[lang] || dict.en;
  for (const p of parts) { val = val?.[p]; if (val === undefined) break; }
  if (val === undefined) {
    val = dict.en;
    for (const p of parts) { val = val?.[p]; if (val === undefined) break; }
  }
  return val ?? key;
}

// Format a translation string with variable substitution.
// Replaces %@, %lld, %1$lld, %2$lld placeholders with provided args in order.
export function tf(lang, key, ...args) {
  let str = t(lang, key);
  args.forEach((arg) => {
    str = str.replace(/%@|%lld|%1\$lld|%2\$lld/, arg);
  });
  return str;
}